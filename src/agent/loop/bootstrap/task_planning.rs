/// Completion-contract signals classified by the task-assessment model. The
/// runtime installs them only when the full contract is present and valid;
/// partial output never refines a hard completion decision.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub(crate) struct PlannedContractSignals {
    /// `low`, `medium`, or `high`. Permission-affecting refinements require
    /// medium or high confidence.
    #[serde(default)]
    pub confidence: Option<String>,
    #[serde(default)]
    pub expects_mutation: Option<bool>,
    #[serde(default)]
    pub requires_observation: Option<bool>,
    /// Positive outcome effects required for completion. These refine proof
    /// obligations; they do not grant permission to perform an action.
    #[serde(default)]
    pub required_effects: Option<Vec<String>>,
    #[serde(default)]
    pub task_kind: Option<String>,
    /// `allowed`, `read_only`, or `scoped`. This separates a global
    /// observation-only constraint from a request that merely forbids one
    /// operation while still requiring other changes.
    #[serde(default)]
    pub mutation_scope: Option<String>,
    /// Operation-specific constraints such as `deploy` or `send`.
    #[serde(default)]
    pub forbidden_actions: Vec<String>,
    /// Exact, verbatim spans from the current user request that support a
    /// negative mutation constraint.
    #[serde(default)]
    pub constraint_evidence: Vec<String>,
    /// `allowed` or `forbidden`. This is independent of mutation scope: a
    /// user can request a conceptual or evidence-limited answer while also
    /// prohibiting every tool call.
    #[serde(default)]
    pub tool_scope: Option<String>,
    /// Exact tool identifiers authorized when `tool_scope=restricted`.
    #[serde(default)]
    pub allowed_tool_names: Vec<String>,
    /// Capability domains explicitly forbidden for this request while other
    /// tools remain allowed. This is a typed deny-set, not a tool-name list.
    #[serde(default)]
    pub forbidden_tool_scopes: Vec<crate::traits::ToolSemanticScope>,
    /// Exact current-user spans grounding either `tool_scope=forbidden` or
    /// every entry in `forbidden_tool_scopes`.
    #[serde(default)]
    pub tool_constraint_evidence: Vec<String>,
    /// Exact user-authored labels that a substantive final response must
    /// contain (for example requested report fields or fixed verdict labels).
    #[serde(default)]
    pub required_response_fields: Vec<String>,
    /// Typed evidence requirements consumed directly by completion checks.
    #[serde(default)]
    pub minimum_sources: Option<u8>,
    #[serde(default)]
    pub requires_primary_sources: Option<bool>,
    #[serde(default)]
    pub requires_exact_history: Option<bool>,
    /// Independently material information needs. The assessor describes the
    /// evidence; it never chooses or authorizes a tool.
    #[serde(default)]
    pub evidence_requirements: Option<Vec<crate::traits::RequestEvidenceRequirement>>,
    /// Machine invocations whose occurrence/result is itself part of the
    /// requested outcome. This remains separate from subject-matter evidence.
    #[serde(default)]
    pub required_invocations: Option<Vec<crate::traits::RequestReceiptPredicate>>,
    /// Least-privilege local filesystem authority for the task. Paths are
    /// structural resource identifiers; read/write roles are semantic output,
    /// not inferred later from command prose.
    #[serde(default)]
    pub filesystem_access: Option<PlannedFilesystemAccess>,
    /// Exact user-authored path or project name selected semantically for this
    /// turn. The runtime resolves and validates it before changing scope.
    #[serde(default)]
    pub project_reference: Option<String>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub(crate) struct PlannedFilesystemAccess {
    #[serde(default)]
    pub execution_cwd: Option<String>,
    #[serde(default)]
    pub read_paths: Vec<String>,
    #[serde(default)]
    pub write_paths: Vec<String>,
}

/// Semantic task shape used by the orchestration router. The route decision is
/// deliberately separate from the step plan: autonomous models need routing,
/// not a second model dictating how to perform the work.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub(crate) struct PlannedTaskShape {
    /// `inline` for work the current agent loop should finish, `durable` for
    /// work that should become a persistent background goal.
    #[serde(default)]
    pub execution_mode: Option<String>,
    /// `low`, `medium`, or `high`.
    #[serde(default)]
    pub confidence: Option<String>,
    #[serde(default)]
    pub independent_workstreams: Option<u8>,
    #[serde(default)]
    pub requires_background_continuation: Option<bool>,
    /// True only when the current inline run has another independent action it
    /// can perform immediately after starting a background process.
    #[serde(default)]
    pub continue_inline_after_background_start: Option<bool>,
    /// Relationship of this turn to persisted dialogue state.
    #[serde(default)]
    pub request_relationship: Option<String>,
    /// Exact prior user-message ID selected from relationship-assessment
    /// context. Required for `continuation`; null for independent requests.
    #[serde(default)]
    pub antecedent_user_message_id: Option<String>,
    /// Typed tool/resource domain for the request.
    #[serde(default)]
    pub semantic_scope: Option<String>,
}

