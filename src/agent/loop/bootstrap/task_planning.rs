fn decode_optional_field<T: serde::de::DeserializeOwned>(
    object: &serde_json::Map<String, Value>,
    name: &str,
) -> Option<T> {
    object
        .get(name)
        .cloned()
        .and_then(|value| serde_json::from_value(value).ok())
}

fn decode_array_items<T: serde::de::DeserializeOwned>(
    object: &serde_json::Map<String, Value>,
    name: &str,
) -> Vec<T> {
    object
        .get(name)
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|value| serde_json::from_value(value.clone()).ok())
        .collect()
}

/// Decode contract fields independently so malformed authority, response, or
/// routing data cannot erase valid lifecycle obligations. This function only
/// consumes typed JSON fields; it never reads or classifies request prose.
fn decode_planned_contract_candidate(value: &Value) -> Option<PlannedContractSignals> {
    let object = value.as_object()?;
    let filesystem_access = object
        .get("filesystem_access")
        .and_then(Value::as_object)
        .map(|filesystem| PlannedFilesystemAccess {
            execution_cwd: decode_optional_field(filesystem, "execution_cwd"),
            read_paths: decode_array_items(filesystem, "read_paths"),
            write_paths: decode_array_items(filesystem, "write_paths"),
            read_roots: decode_array_items(filesystem, "read_roots"),
            write_roots: decode_array_items(filesystem, "write_roots"),
        });
    let evidence_requirements = object
        .contains_key("evidence_requirements")
        .then(|| decode_array_items(object, "evidence_requirements"));
    let required_invocations = object
        .contains_key("required_invocations")
        .then(|| decode_array_items(object, "required_invocations"));
    let dispatch_stop_rules = object
        .contains_key("dispatch_stop_rules")
        .then(|| decode_array_items(object, "dispatch_stop_rules"));

    Some(PlannedContractSignals {
        confidence: decode_optional_field(object, "confidence"),
        expects_mutation: decode_optional_field(object, "expects_mutation"),
        requires_observation: decode_optional_field(object, "requires_observation"),
        required_effects: object
            .contains_key("required_effects")
            .then(|| decode_array_items(object, "required_effects")),
        task_kind: decode_optional_field(object, "task_kind"),
        mutation_scope: decode_optional_field(object, "mutation_scope"),
        forbidden_actions: decode_array_items(object, "forbidden_actions"),
        constraint_evidence: Vec::new(),
        tool_scope: decode_optional_field(object, "tool_scope"),
        allowed_tool_names: decode_array_items(object, "allowed_tool_names"),
        forbidden_tool_scopes: decode_array_items(object, "forbidden_tool_scopes"),
        tool_constraint_evidence: Vec::new(),
        required_response_fields: decode_array_items(object, "required_response_fields"),
        response_contract: decode_optional_field(object, "response_contract"),
        minimum_sources: decode_optional_field(object, "minimum_sources"),
        requires_primary_sources: decode_optional_field(object, "requires_primary_sources"),
        requires_exact_history: decode_optional_field(object, "requires_exact_history"),
        evidence_requirements,
        required_invocations,
        dispatch_stop_rules,
        filesystem_access,
        project_reference: decode_optional_field(object, "project_reference"),
    })
}

const TASK_RELATIONSHIP_SCHEMA_VERSION: u16 = 1;

fn confidence_is_sufficient(value: Option<&str>) -> bool {
    matches!(
        value.map(|value| value.trim().to_ascii_lowercase()),
        Some(value) if matches!(value.as_str(), "medium" | "high")
    )
}

pub(crate) fn planned_contract_is_confident(
    signals: &PlannedContractSignals,
    task_shape: Option<&PlannedTaskShape>,
) -> bool {
    confidence_is_sufficient(
        signals
            .confidence
            .as_deref()
            .or_else(|| task_shape.and_then(|shape| shape.confidence.as_deref())),
    )
}

pub(crate) fn planned_task_relationship_is_complete(shape: &PlannedTaskShape) -> bool {
    let relationship = shape
        .request_relationship
        .as_deref()
        .map(str::trim)
        .unwrap_or_default();
    let antecedent = shape
        .antecedent_user_message_id
        .as_deref()
        .map(str::trim)
        .filter(|value| !value.is_empty());
    confidence_is_sufficient(shape.confidence.as_deref())
        && shape.semantic_scope.as_deref().is_some_and(|scope| {
            matches!(
                scope.trim(),
                "none"
                    | "goal_state"
                    | "user_memory"
                    | "conversation_history"
                    | "external_remote"
                    | "local_workspace"
                    | "host_local"
            )
        })
        && match relationship {
            // The semantic compiler owns the relationship class. Exact
            // identity belongs to the deterministic dialogue-state resolver,
            // which may bind an omitted ID only when one unambiguous request
            // antecedent exists and otherwise fails closed to a new request.
            "continuation" => true,
            "new_request" | "clarification_answer" | "courtesy" => antecedent.is_none(),
            _ => false,
        }
}

/// Hard completion decisions require a complete semantic contract. This is a
/// schema/invariant check, not a text classifier.
pub(crate) fn planned_contract_is_complete(signals: &PlannedContractSignals) -> bool {
    let Some(expects_mutation) = signals.expects_mutation else {
        return false;
    };
    let Some(task_kind) = signals
        .task_kind
        .as_deref()
        .and_then(crate::agent::parse_planned_task_kind)
    else {
        return false;
    };
    if signals.requires_observation.is_none()
        || signals.minimum_sources.is_none()
        || signals.requires_primary_sources.is_none()
        || signals.requires_exact_history.is_none()
        || signals.evidence_requirements.is_none()
        || signals.required_invocations.is_none()
        || signals.dispatch_stop_rules.is_none()
        || signals.filesystem_access.is_none()
        || signals.tool_scope.is_none()
    {
        return false;
    }

    // The task kind and effect contract describe the same lifecycle. Reject a
    // planner result that asks the runtime to wait for mutation on an
    // observational task (or declares a change complete without any mutation).
    // This is a typed schema invariant, independent of the request's wording.
    let mutation_capable_kind = matches!(
        task_kind,
        crate::agent::CompletionTaskKind::Change
            | crate::agent::CompletionTaskKind::Deliver
            | crate::agent::CompletionTaskKind::Schedule
            | crate::agent::CompletionTaskKind::Monitor
    );
    if expects_mutation != mutation_capable_kind {
        return false;
    }

    let Some(scope) = signals
        .mutation_scope
        .as_deref()
        .map(|value| value.trim().to_ascii_lowercase())
        .filter(|scope| {
            matches!(
                scope.as_str(),
                "allowed" | "read_only" | "read-only" | "scoped"
            )
        })
    else {
        return false;
    };

    if matches!(scope.as_str(), "read_only" | "read-only") && expects_mutation {
        return false;
    }
    if scope == "allowed" && !signals.forbidden_actions.is_empty() {
        return false;
    }
    if scope == "scoped" && signals.forbidden_actions.is_empty() {
        return false;
    }
    if signals
        .forbidden_actions
        .iter()
        .any(|action| crate::agent::parse_planned_forbidden_action(action).is_none())
    {
        return false;
    }
    let tool_scope = signals
        .tool_scope
        .as_deref()
        .map(|value| value.trim().to_ascii_lowercase())
        .unwrap_or_default();
    if !matches!(tool_scope.as_str(), "allowed" | "forbidden" | "restricted")
        || tool_scope == "allowed" && !signals.allowed_tool_names.is_empty()
        || tool_scope == "forbidden" && !signals.allowed_tool_names.is_empty()
        || tool_scope == "restricted" && signals.allowed_tool_names.is_empty()
        || signals.allowed_tool_names.len() > 8
        || signals.allowed_tool_names.iter().any(|name| {
            name.is_empty()
                || name.len() > 80
                || !name.bytes().all(|byte| {
                    byte.is_ascii_lowercase()
                        || byte.is_ascii_digit()
                        || matches!(byte, b'_' | b'-')
                })
        })
    {
        return false;
    }
    let minimum_sources = signals.minimum_sources.unwrap_or_default();
    if minimum_sources > 20
        || (signals.requires_primary_sources == Some(true) && minimum_sources == 0)
    {
        return false;
    }

    let evidence_requirements = signals.evidence_requirements.as_deref().unwrap_or_default();
    let required_invocations = signals.required_invocations.as_deref().unwrap_or_default();
    let dispatch_stop_rules = signals.dispatch_stop_rules.as_deref().unwrap_or_default();
    let filesystem_access = signals.filesystem_access.as_ref().expect("checked above");
    let has_filesystem_read_capability =
        !filesystem_access.read_paths.is_empty() || !filesystem_access.read_roots.is_empty();
    let has_process_context = filesystem_access.execution_cwd.is_some();
    if evidence_requirements.len() > 8
        || required_invocations.len() > 8
        || dispatch_stop_rules.len() > 8
        || filesystem_access.read_paths.len() > 8
        || filesystem_access.write_paths.len() > 8
        || filesystem_access.read_roots.len() > 8
        || filesystem_access.write_roots.len() > 8
        || filesystem_access
            .execution_cwd
            .as_deref()
            .is_some_and(|path| path.trim().is_empty() || path.chars().count() > 1000)
        || filesystem_access
            .read_paths
            .iter()
            .chain(&filesystem_access.write_paths)
            .chain(&filesystem_access.read_roots)
            .chain(&filesystem_access.write_roots)
            .any(|path| path.trim().is_empty() || path.chars().count() > 1000)
        || !expects_mutation
            && (!filesystem_access.write_paths.is_empty()
                || !filesystem_access.write_roots.is_empty())
        // A read capability or process context is an execution input, not
        // conversational metadata. It cannot coexist with a zero-observation,
        // zero-invocation lifecycle even if the semantic producer mislabeled
        // the task kind. This is a typed cross-field invariant; no request text
        // is inspected here.
        || has_filesystem_read_capability && signals.requires_observation != Some(true)
        || has_process_context
            && !expects_mutation
            && evidence_requirements.is_empty()
            && required_invocations.is_empty()
        // A check is an evidence-producing lifecycle kind. Treating it as a
        // zero-observation answer would let the model assert current-run or
        // current-state facts without any proof edge.
        || task_kind == crate::agent::CompletionTaskKind::Check
            && signals.requires_observation != Some(true)
        || signals.requires_observation == Some(true)
            && evidence_requirements.is_empty()
            && required_invocations.is_empty()
        || signals.requires_observation == Some(false)
            && (!evidence_requirements.is_empty() || !required_invocations.is_empty())
        || task_kind == crate::agent::CompletionTaskKind::Check
            && tool_scope == "restricted"
            && !evidence_requirements.iter().any(|requirement| {
                requirement.receipt.as_ref().is_some_and(|receipt| {
                    receipt
                        .tool_names
                        .iter()
                        .any(|name| signals.allowed_tool_names.contains(name))
                })
            })
            && !required_invocations.iter().any(|receipt| {
                receipt
                    .tool_names
                    .iter()
                    .any(|name| signals.allowed_tool_names.contains(name))
            })
        || tool_scope == "restricted"
            && evidence_requirements.iter().any(|requirement| {
                requirement.receipt.as_ref().is_some_and(|receipt| {
                    receipt
                        .tool_names
                        .iter()
                        .any(|name| !signals.allowed_tool_names.contains(name))
                })
            })
        || evidence_requirements.iter().any(|requirement| {
            let summary_len = requirement.summary.trim().chars().count();
            summary_len == 0
                || summary_len > 240
                || requirement.acceptable_scopes.is_empty()
                || requirement.acceptable_scopes.len() > 3
                || !requirement.required_content_markers.is_empty()
                || requirement.receipt.as_ref().is_some_and(|receipt| {
                    receipt.is_empty()
                        || receipt.tool_names.len() > 8
                        || receipt.tool_names.iter().any(|name| {
                            name.is_empty()
                                || name.len() > 80
                                || !name.bytes().all(|byte| {
                                    byte.is_ascii_lowercase()
                                        || byte.is_ascii_digit()
                                        || matches!(byte, b'_' | b'-')
                                })
                        })
                        || receipt.exit_codes.len() > 16
                        || receipt.outcome_statuses.len() > 6
                        || receipt
                            .min_invocations
                            .is_some_and(|limit| !(1..=16).contains(&limit))
                        || receipt
                            .max_invocations
                            .is_some_and(|limit| !(1..=16).contains(&limit))
                        || receipt
                            .min_invocations
                            .zip(receipt.max_invocations)
                            .is_some_and(|(minimum, maximum)| minimum > maximum)
                })
                // Outcome observations are receipt facts. Requiring their
                // labels to appear in returned content recreates a second,
                // contradictory proof contract.
                || requirement.purpose == crate::traits::EvidencePurpose::Outcome
                    && (!requirement.required_content_markers.is_empty()
                        || requirement
                            .receipt
                            .as_ref()
                            .is_none_or(crate::traits::RequestReceiptPredicate::is_empty))
                // Exact targets come only from structural request parsing.
                || requirement.target.is_some()
                || !crate::agent::inquiry::requirement_has_builtin_evidence_route(requirement)
        })
        || required_invocations.iter().any(|receipt| {
            receipt.is_empty()
                || receipt.tool_names.len() != 1
                || receipt.tool_names.iter().any(|name| {
                    name.is_empty()
                        || name.len() > 80
                        || !name.bytes().all(|byte| {
                            byte.is_ascii_lowercase()
                                || byte.is_ascii_digit()
                                || matches!(byte, b'_' | b'-')
                        })
                })
                || receipt.exit_codes.len() > 16
                || receipt.outcome_statuses.len() > 6
                || receipt
                    .min_invocations
                    .is_some_and(|limit| !(1..=16).contains(&limit))
                || receipt
                    .max_invocations
                    .is_some_and(|limit| !(1..=16).contains(&limit))
                || receipt
                    .min_invocations
                    .zip(receipt.max_invocations)
                    .is_some_and(|(minimum, maximum)| minimum > maximum)
                || tool_scope == "restricted"
                    && receipt
                        .tool_names
                        .iter()
                        .any(|name| !signals.allowed_tool_names.contains(name))
        })
        || dispatch_stop_rules.iter().any(|rule| {
            rule.trigger.is_empty()
                || !required_invocations.contains(&rule.trigger)
                || (rule.blocked_tool_names.is_empty() && rule.blocked_receipt_kinds.is_empty())
                || rule.blocked_tool_names.len() > 8
                || rule.blocked_receipt_kinds.len() > 3
                || rule.blocked_tool_names.iter().any(|name| {
                    name.is_empty()
                        || name.len() > 80
                        || !name.bytes().all(|byte| {
                            byte.is_ascii_lowercase()
                                || byte.is_ascii_digit()
                                || matches!(byte, b'_' | b'-')
                        })
                })
        })
    {
        return false;
    }
    if signals.requires_exact_history == Some(true)
        && !evidence_requirements.iter().any(|requirement| {
            requirement
                .acceptable_scopes
                .contains(&crate::traits::ToolSemanticScope::ConversationHistory)
                && requirement.purpose == crate::traits::EvidencePurpose::HistoricalRecord
                && requirement.minimum_authority == crate::traits::EvidenceAuthority::Canonical
        })
    {
        return false;
    }

    let Some(effect_names) = signals.required_effects.as_deref() else {
        return false;
    };
    if !expects_mutation {
        return effect_names.is_empty();
    }
    let Some(effects) = crate::agent::parse_planned_mutation_effects(effect_names) else {
        return false;
    };
    if effects.is_empty() {
        return false;
    }
    if effects.contains(crate::traits::ToolMutationEffects::DESTRUCTIVE) {
        return false;
    }

    // The current bitset represents one set of required outcomes, so it cannot
    // distinguish a generic remote mutation from a second, independent remote
    // outcome. Reject broad+specific combinations rather than demanding two
    // receipts for one delivery/deployment. A richer obligation list can model
    // genuinely independent outcomes in the future.
    if effects.contains(crate::traits::ToolMutationEffects::REMOTE_MUTATION)
        && effects.intersects(
            crate::traits::ToolMutationEffects::REMOTE_DEPLOY
                .union(crate::traits::ToolMutationEffects::EXTERNAL_DELIVERY),
        )
    {
        return false;
    }
    if task_kind == crate::agent::CompletionTaskKind::Deliver
        && !effects.contains(crate::traits::ToolMutationEffects::EXTERNAL_DELIVERY)
    {
        return false;
    }
    true
}

/// Validate the authoritative lifecycle product without coupling it to
/// independent sibling lanes such as mutation/tool authority, presentation,
/// or research policy. A malformed sibling may still be quarantined by the
/// contract compiler, but the execution lifecycle is usable only when its
/// core and proof graph agree. This is intentionally narrower than
/// `planned_contract_is_complete`.
/// Normalize a producer's lifecycle lanes where the typed signals already
/// determine the answer. A contract whose lanes merely disagree in a way the
/// stronger lane resolves (obligations present but `requires_observation`
/// unset; a non-mutating task labelled with a mutating kind) is repaired
/// rather than discarded — discarding it hands authority to a lower-priority
/// model that may return a weaker contract for the same request. Returns the
/// lanes that were repaired. Lanes that need content (missing obligations for
/// an observation task, invalid effects) are never invented here.
pub(crate) fn repair_planned_contract_lifecycle(
    signals: &mut PlannedContractSignals,
) -> Vec<&'static str> {
    let mut repaired = Vec::new();
    let has_proof_obligation = signals
        .evidence_requirements
        .as_deref()
        .is_some_and(|evidence| !evidence.is_empty())
        || signals
            .required_invocations
            .as_deref()
            .is_some_and(|invocations| !invocations.is_empty());
    let has_effects = signals
        .required_effects
        .as_deref()
        .is_some_and(|effects| !effects.is_empty());

    if signals.expects_mutation.is_none() {
        signals.expects_mutation = Some(has_effects);
        repaired.push("expects_mutation_from_effects");
    }
    if signals.requires_observation.is_none() {
        signals.requires_observation = Some(has_proof_obligation);
        repaired.push("requires_observation_from_obligations");
    }
    if signals.requires_observation == Some(false) && has_proof_obligation {
        // Typed obligations are the stronger signal than the boolean.
        signals.requires_observation = Some(true);
        repaired.push("requires_observation_from_obligations");
    }
    let expects_mutation = signals.expects_mutation.unwrap_or(false);
    let requires_observation = signals.requires_observation.unwrap_or(false);
    if !expects_mutation && signals.required_effects.is_none() {
        signals.required_effects = Some(Vec::new());
        repaired.push("required_effects_empty");
    }
    if !requires_observation {
        if signals.evidence_requirements.is_none() {
            signals.evidence_requirements = Some(Vec::new());
            repaired.push("evidence_requirements_empty");
        }
        if signals.required_invocations.is_none() {
            signals.required_invocations = Some(Vec::new());
            repaired.push("required_invocations_empty");
        }
    }
    let task_kind = signals
        .task_kind
        .as_deref()
        .and_then(crate::agent::parse_planned_task_kind);
    let mutation_capable = |kind: crate::agent::CompletionTaskKind| {
        matches!(
            kind,
            crate::agent::CompletionTaskKind::Change
                | crate::agent::CompletionTaskKind::Deliver
                | crate::agent::CompletionTaskKind::Schedule
                | crate::agent::CompletionTaskKind::Monitor
        )
    };
    match task_kind {
        Some(kind) if !expects_mutation && mutation_capable(kind) => {
            signals.task_kind = Some(
                if requires_observation {
                    "check"
                } else {
                    "answer"
                }
                .to_string(),
            );
            repaired.push("task_kind_non_mutating");
        }
        Some(kind) if expects_mutation && !mutation_capable(kind) => {
            signals.task_kind = Some("change".to_string());
            repaired.push("task_kind_mutating");
        }
        Some(crate::agent::CompletionTaskKind::Check) if !requires_observation => {
            signals.task_kind = Some("answer".to_string());
            repaired.push("task_kind_check_without_observation");
        }
        None if signals.task_kind.is_none() => {
            signals.task_kind = Some(
                if expects_mutation {
                    "change"
                } else if requires_observation {
                    "check"
                } else {
                    "answer"
                }
                .to_string(),
            );
            repaired.push("task_kind_from_lanes");
        }
        _ => {}
    }
    repaired
}

/// Typed proof obligations from a higher-priority producer's partial (but
/// incoherent) assessment outrank a lower-priority producer's obligation-free
/// contract for the same request. Obligations only demand more evidence and
/// the strictest attenuations only remove authority, so carrying them over
/// can never widen what the run may do. Returns the strengthened plan when
/// the merge is coherent; otherwise the complete plan unchanged.
pub(crate) fn strengthen_plan_from_partial(
    mut plan: TaskPlan,
    partial: Option<&TaskPlan>,
) -> TaskPlan {
    let Some(partial_contract) = partial.and_then(|partial| partial.contract.as_ref()) else {
        return plan;
    };
    let Some(contract) = plan.contract.as_mut() else {
        return plan;
    };
    let has_obligations = |signals: &PlannedContractSignals| {
        signals
            .evidence_requirements
            .as_deref()
            .is_some_and(|evidence| !evidence.is_empty())
            || signals
                .required_invocations
                .as_deref()
                .is_some_and(|invocations| !invocations.is_empty())
    };
    let mut merged = contract.clone();
    let mut changed: Vec<&'static str> = Vec::new();
    if has_obligations(partial_contract)
        && !has_obligations(&merged)
        && merged.expects_mutation != Some(true)
    {
        merged.evidence_requirements = partial_contract.evidence_requirements.clone();
        merged.required_invocations = partial_contract.required_invocations.clone();
        merged.requires_observation = Some(true);
        if matches!(
            merged
                .task_kind
                .as_deref()
                .and_then(crate::agent::parse_planned_task_kind),
            Some(crate::agent::CompletionTaskKind::Answer)
                | Some(crate::agent::CompletionTaskKind::Conversational)
                | None
        ) {
            merged.task_kind = Some("check".to_string());
        }
        changed.push("obligations_from_higher_priority_partial");
    }
    for scope in &partial_contract.forbidden_tool_scopes {
        if !merged.forbidden_tool_scopes.contains(scope) {
            merged.forbidden_tool_scopes.push(*scope);
            if !changed.contains(&"forbidden_tool_scopes_from_partial") {
                changed.push("forbidden_tool_scopes_from_partial");
            }
        }
    }
    if matches!(
        partial_contract.mutation_scope.as_deref(),
        Some("read_only") | Some("read-only")
    ) && merged.mutation_scope.as_deref() != Some("read_only")
        && merged.expects_mutation != Some(true)
    {
        merged.mutation_scope = Some("read_only".to_string());
        changed.push("read_only_from_partial");
    }
    if changed.is_empty() {
        return plan;
    }
    let _ = repair_planned_contract_lifecycle(&mut merged);
    if planned_contract_lifecycle_incoherence(&merged).is_some() {
        return plan;
    }
    *contract = merged;
    plan.contract_repairs.extend(changed);
    plan
}

/// The first lifecycle lane that makes the contract incoherent, or `None`
/// when it is coherent. Naming the lane is what makes a discarded assessment
/// diagnosable from telemetry.
pub(crate) fn planned_contract_lifecycle_incoherence(
    signals: &PlannedContractSignals,
) -> Option<&'static str> {
    let (Some(expects_mutation), Some(requires_observation), Some(task_kind)) = (
        signals.expects_mutation,
        signals.requires_observation,
        signals
            .task_kind
            .as_deref()
            .and_then(crate::agent::parse_planned_task_kind),
    ) else {
        return Some("missing_lifecycle_lane");
    };
    let mutation_capable = matches!(
        task_kind,
        crate::agent::CompletionTaskKind::Change
            | crate::agent::CompletionTaskKind::Deliver
            | crate::agent::CompletionTaskKind::Schedule
            | crate::agent::CompletionTaskKind::Monitor
    );
    if expects_mutation != mutation_capable {
        return Some("task_kind_mutation_mismatch");
    }
    let Some(effect_names) = signals.required_effects.as_deref() else {
        return Some("missing_required_effects");
    };
    let effects_valid = if expects_mutation {
        crate::agent::parse_planned_mutation_effects(effect_names).is_some_and(|effects| {
            if effects.is_empty()
                || effects.contains(crate::traits::ToolMutationEffects::DESTRUCTIVE)
            {
                return false;
            }
            if effects.contains(crate::traits::ToolMutationEffects::REMOTE_MUTATION)
                && effects.intersects(
                    crate::traits::ToolMutationEffects::REMOTE_DEPLOY
                        .union(crate::traits::ToolMutationEffects::EXTERNAL_DELIVERY),
                )
            {
                return false;
            }
            task_kind != crate::agent::CompletionTaskKind::Deliver
                || effects.contains(crate::traits::ToolMutationEffects::EXTERNAL_DELIVERY)
        })
    } else {
        effect_names.is_empty()
    };
    if !effects_valid {
        return Some("invalid_required_effects");
    }

    let (Some(evidence), Some(invocations)) = (
        signals.evidence_requirements.as_deref(),
        signals.required_invocations.as_deref(),
    ) else {
        return Some("missing_obligation_lane");
    };
    let has_proof_obligation = !evidence.is_empty() || !invocations.is_empty();
    if requires_observation != has_proof_obligation {
        return Some("observation_obligation_mismatch");
    }
    if task_kind == crate::agent::CompletionTaskKind::Check && !requires_observation {
        return Some("check_without_observation");
    }

    if let Some(filesystem) = signals.filesystem_access.as_ref() {
        let has_read_capability =
            !filesystem.read_paths.is_empty() || !filesystem.read_roots.is_empty();
        let has_process_context = filesystem.execution_cwd.is_some();
        if has_read_capability && !requires_observation
            || has_process_context && !expects_mutation && !has_proof_obligation
        {
            return Some("filesystem_without_obligation");
        }
    }
    None
}

#[cfg(test)]
pub(crate) fn planned_contract_lifecycle_is_coherent(signals: &PlannedContractSignals) -> bool {
    planned_contract_lifecycle_incoherence(signals).is_none()
}

/// How much task scaffolding the active model needs.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum TaskAssessmentMode {
    /// Produce a concrete step plan for models that benefit from supervision.
    GuidedPlan,
    /// Classify only the contract and orchestration shape. The primary model
    /// remains responsible for its own approach.
    AutonomousRouting,
}

impl TaskAssessmentMode {
    pub(crate) fn includes_step_plan(self) -> bool {
        matches!(self, Self::GuidedPlan)
    }

    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::GuidedPlan => "guided_plan",
            Self::AutonomousRouting => "autonomous_routing",
        }
    }
}

/// Raw response from the task assessment call.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct TaskPlanResponse {
    #[serde(default = "task_contract_schema_version")]
    schema_version: u16,
    goal: String,
    #[serde(default)]
    steps: Vec<TaskPlanStep>,
    #[serde(default)]
    success_criteria: Vec<String>,
    #[serde(default)]
    contract: Option<PlannedContractSignals>,
    #[serde(default)]
    task_shape: Option<PlannedTaskShape>,
}

const TASK_CONTRACT_SCHEMA_VERSION: u16 = 13;

const fn task_contract_schema_version() -> u16 {
    TASK_CONTRACT_SCHEMA_VERSION
}

fn decode_task_plan_response(envelope: &Value) -> Option<TaskPlanResponse> {
    let object = envelope.as_object()?;
    let schema_version = object
        .get("schema_version")
        .and_then(Value::as_u64)
        .and_then(|version| u16::try_from(version).ok())
        .unwrap_or_default();
    Some(TaskPlanResponse {
        schema_version,
        goal: object
            .get("goal")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string(),
        steps: decode_array_items(object, "steps"),
        success_criteria: decode_array_items(object, "success_criteria"),
        contract: object
            .get("contract")
            .and_then(decode_planned_contract_candidate),
        task_shape: decode_optional_field(object, "task_shape"),
    })
}

fn migrate_task_plan_response(mut parsed: TaskPlanResponse) -> Option<TaskPlanResponse> {
    match parsed.schema_version {
        TASK_CONTRACT_SCHEMA_VERSION => Some(parsed),
        7..=12 => {
            if let Some(contract) = parsed.contract.as_mut() {
                let invocations = contract.required_invocations.get_or_insert_with(Vec::new);
                for requirement in contract
                    .evidence_requirements
                    .as_mut()
                    .into_iter()
                    .flatten()
                {
                    // Schema 7/8 combined subject evidence and requested
                    // invocation evidence. Preserve the typed receipt in the
                    // new lane, while retiring prose-marker authority.
                    if let Some(receipt) = requirement.receipt.clone() {
                        if !invocations.contains(&receipt) {
                            invocations.push(receipt);
                        }
                    }
                    requirement.required_content_markers.clear();
                }
                contract
                    .filesystem_access
                    .get_or_insert_with(PlannedFilesystemAccess::default);
                contract.dispatch_stop_rules.get_or_insert_with(Vec::new);
            }
            parsed.schema_version = TASK_CONTRACT_SCHEMA_VERSION;
            Some(parsed)
        }
        _ => None,
    }
}

fn uses_current_receipt_dialect(contract: Option<&PlannedContractSignals>) -> bool {
    let Some(contract) = contract else {
        return true;
    };
    contract
        .required_invocations
        .as_deref()
        .unwrap_or_default()
        .iter()
        .chain(
            contract
                .evidence_requirements
                .as_deref()
                .unwrap_or_default()
                .iter()
                .filter_map(|requirement| requirement.receipt.as_ref()),
        )
        .all(|receipt| {
            receipt.outcome_condition.is_some()
                && receipt.outcome_statuses.is_empty()
                && receipt.contract_rejected.is_none()
        })
}

/// Result of the task-start assessment call.
#[derive(Debug, Clone)]
#[allow(dead_code)]
pub(crate) struct TaskPlan {
    pub goal: String,
    pub steps: Vec<TaskPlanStep>,
    pub success_criteria: Vec<String>,
    pub contract: Option<PlannedContractSignals>,
    pub task_shape: Option<PlannedTaskShape>,
    pub mode: TaskAssessmentMode,
    /// True only when the completion producer emitted one internally coherent
    /// lifecycle contract. Partial products may still carry attenuating
    /// authority, but they cannot authorize execution or completion.
    pub contract_complete: bool,
    /// The lifecycle lane that made the contract incomplete, when it is.
    pub incoherence: Option<&'static str>,
    /// Lanes normalized from their typed signals before the coherence check.
    pub contract_repairs: Vec<&'static str>,
}

fn decode_task_plan_result(
    response: &ProviderResponse,
    mode: TaskAssessmentMode,
) -> Result<TaskPlan, String> {
    let content = response
        .content
        .as_deref()
        .ok_or_else(|| "empty_structured_response".to_string())?;
    let json_str = crate::utils::extract_json_object(content)
        .ok_or_else(|| "missing_json_object".to_string())?;
    let envelope: Value =
        serde_json::from_str(&json_str).map_err(|error| format!("invalid_json: {error}"))?;
    let parsed =
        decode_task_plan_response(&envelope).ok_or_else(|| "response_not_object".to_string())?;
    let received_schema_version = parsed.schema_version;
    if received_schema_version == TASK_CONTRACT_SCHEMA_VERSION
        && !uses_current_receipt_dialect(parsed.contract.as_ref())
    {
        return Err("invalid_current_receipt_dialect".to_string());
    }
    let parsed = migrate_task_plan_response(parsed).ok_or_else(|| {
        format!(
            "unsupported_schema_version:{received_schema_version};supported:{TASK_CONTRACT_SCHEMA_VERSION}"
        )
    })?;
    // Decode the semantic envelope as a product of independent lanes. Keep a
    // partial product so valid attenuating constraints can survive, but mark
    // it non-authoritative for execution and completion. The producer loop
    // uses this typed invariant to repair or fail over before bootstrap.
    if parsed.contract.is_none() && parsed.task_shape.is_none() && parsed.steps.is_empty() {
        return Err("empty_semantic_envelope".to_string());
    }

    let mut parsed = parsed;
    let mut contract_repairs = Vec::new();
    let mut incoherence = None;
    if let Some(contract) = parsed.contract.as_mut() {
        contract_repairs = repair_planned_contract_lifecycle(contract);
        incoherence = planned_contract_lifecycle_incoherence(contract);
    }
    let contract_complete = parsed.contract.is_some() && incoherence.is_none();
    if !contract_repairs.is_empty() {
        info!(
            repairs = ?contract_repairs,
            complete = contract_complete,
            "Repaired task assessment lifecycle lanes from their typed signals"
        );
    }

    let mut steps = parsed.steps;
    let mut success_criteria = parsed.success_criteria;
    if !mode.includes_step_plan() {
        steps.clear();
        success_criteria.clear();
    }
    steps.truncate(MAX_PLAN_STEPS);
    Ok(TaskPlan {
        goal: parsed.goal,
        steps,
        success_criteria,
        contract: parsed.contract,
        task_shape: parsed.task_shape,
        mode,
        contract_complete,
        incoherence,
        contract_repairs,
    })
}

/// Compiled policy for automatic memory access and persistence during one task.
///
/// This is deliberately derived from the same grounded semantic assessment
/// that owns tool constraints. Prompt retrieval, message-span projection, and
/// post-task learning must all consume this one value; none of those stages is
/// allowed to independently reinterpret the user's wording.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum MemoryPipelinePolicy {
    Allowed,
    SuppressedByCurrentContract,
    SuppressedByAssessment,
    SuppressedAssessmentUnavailable,
}

impl MemoryPipelinePolicy {
    pub(crate) const fn allows_memory(self) -> bool {
        matches!(self, Self::Allowed)
    }

    pub(crate) const fn reason_code(self) -> &'static str {
        match self {
            Self::Allowed => "allowed_by_compiled_contract",
            Self::SuppressedByCurrentContract => "inherited_contract_denies_user_memory",
            Self::SuppressedByAssessment => "current_assessment_denies_user_memory",
            Self::SuppressedAssessmentUnavailable => "assessment_unavailable_fail_closed",
        }
    }
}

/// Compile the task-local automatic-memory policy from typed lifecycle state.
/// Assessment failure is fail-closed for *automatic* memory only; normal tool
/// availability remains governed by the completion contract in the main loop.
pub(crate) fn compile_memory_pipeline_policy(
    current_contract: &crate::agent::CompletionContract,
    semantic_contract_applied: bool,
) -> MemoryPipelinePolicy {
    if current_contract
        .forbidden_tool_scopes
        .contains(&crate::traits::ToolSemanticScope::UserMemory)
    {
        return if semantic_contract_applied {
            MemoryPipelinePolicy::SuppressedByAssessment
        } else {
            MemoryPipelinePolicy::SuppressedByCurrentContract
        };
    }
    if !semantic_contract_applied {
        return MemoryPipelinePolicy::SuppressedAssessmentUnavailable;
    }
    if !current_contract.allowed_tool_names.is_empty()
        && !current_contract.allowed_tool_names.iter().any(|name| {
            matches!(
                name.as_str(),
                "manage_memories" | "manage_people" | "remember_fact" | "share_memory"
            )
        })
    {
        MemoryPipelinePolicy::SuppressedByAssessment
    } else {
        MemoryPipelinePolicy::Allowed
    }
}

const MAX_PLAN_STEPS: usize = 7;
// Aggregate semantic-producer deadlines. Candidates are bounded failover
// attempts under one logical producer envelope; valid results are selected by
// configured priority, never by response wording or latency.
const TASK_ASSESSMENT_DEFAULT_ATTEMPT_TIMEOUT: Duration = Duration::from_secs(20);
const TASK_ASSESSMENT_MAX_ATTEMPT_TIMEOUT: Duration = Duration::from_secs(45);
const TASK_ASSESSMENT_MAX_TOTAL_TIMEOUT: Duration = Duration::from_secs(90);
const TASK_RELATIONSHIP_TOTAL_TIMEOUT: Duration = Duration::from_secs(45);

/// JSON-object mode is rejected by a number of OpenAI-compatible gateways
/// unless the prompt contains a provider-specific lowercase marker.  The
/// daemon's semantic producers should not depend on prompt spelling.  A
/// permissive named schema requests the same object protocol while leaving
/// the domain parser as the authoritative validator for optional fields.
fn typed_object_response_mode(name: &str) -> crate::traits::ResponseMode {
    crate::traits::ResponseMode::JsonSchema {
        name: name.to_string(),
        schema: json!({
            "type": "object",
            "additionalProperties": true
        }),
        strict: false,
    }
}

/// Convert a model's observed p95 into a bounded producer deadline.  The
/// default is deliberately large enough for a normal richer contract, while
/// historical latency lets a slower configured model retain time without
/// giving any single candidate an unbounded call.
fn observed_assessment_budget(observed_latency_ms: Option<u64>) -> Duration {
    let observed = observed_latency_ms
        .map(Duration::from_millis)
        .map(|latency| latency.saturating_mul(2))
        .unwrap_or(TASK_ASSESSMENT_DEFAULT_ATTEMPT_TIMEOUT);
    observed
        .max(TASK_ASSESSMENT_DEFAULT_ATTEMPT_TIMEOUT)
        .min(TASK_ASSESSMENT_MAX_ATTEMPT_TIMEOUT)
}

#[cfg(test)]
fn bounded_attempt_timeout(remaining: Duration, requested: Duration) -> Option<Duration> {
    (!remaining.is_zero() && !requested.is_zero()).then(|| remaining.min(requested))
}

/// Divide the remaining relationship envelope using the same fair allocator
/// as the contract lane. A relationship producer is not a special class of
/// provider: every configured candidate receives a bounded share, and unused
/// time is naturally returned to later candidates after a fast failure.
fn relationship_attempt_timeout(
    remaining: std::time::Duration,
    candidates_left: usize,
) -> Option<std::time::Duration> {
    (candidates_left > 0 && !remaining.is_zero())
        .then(|| remaining / u32::try_from(candidates_left).unwrap_or(u32::MAX))
}

