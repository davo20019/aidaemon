/// Assess the user's request before its main loop. Guided models receive step
/// scaffolding; autonomous models receive only semantic routing/obligations.
///
/// Returns None if the assessment call fails, times out, or returns
/// unparseable JSON. Failure is silent and callers continue without a plan.
#[allow(dead_code)]
pub(crate) async fn generate_task_plan(
    provider: Arc<dyn ModelProvider>,
    model: &str,
    user_text: &str,
    conversation_context: Option<&str>,
    mode: TaskAssessmentMode,
    telemetry: Option<PlannerTelemetryCtx<'_>>,
) -> Option<TaskPlan> {
    let system = "You are a task assessment router. Read the request semantically in its \
                  original language and return ONLY valid JSON, with no markdown fences.";

    // Include conversation context from the sliding window so the planner
    // has the same narrative as the main LLM. Without this, short follow-ups
    // like "and for ibuprofen?" lose the original intent from earlier turns.
    let context_block = conversation_context
        .filter(|ctx| !ctx.is_empty())
        .map(|ctx| format!("Recent conversation context:\n{}\n\n", ctx))
        .unwrap_or_default();

    let plan_instructions = if mode.includes_step_plan() {
        "- Return 2-7 concrete steps and concrete success criteria.\n\
         - tool_hint is advisory.\n\
         - Keep each distinct action in its own step; do not collapse build, run, fix, \
           deploy, and verify into one step.\n\
         - When creating a file that processes other files, begin by inspecting the \
           target format."
    } else {
        "- Return steps=[] and success_criteria=[]. Do not plan the model's approach; \
           this call only classifies routing and obligations."
    };

    let user_prompt = format!(
        "{context_block}Assess this user request.\n\n\
         User request: \"{user_text}\"\n\n\
         Return exactly this JSON shape:\n\
         {{\n\
           \"schema_version\": 9,\n\
           \"goal\": \"one-line semantic summary\",\n\
           \"steps\": [],\n\
           \"success_criteria\": [],\n\
           \"contract\": {{\n\
             \"confidence\": \"low|medium|high\",\n\
             \"task_kind\": \"conversational|answer|check|find|change|deliver|schedule|monitor|diagnose\",\n\
             \"expects_mutation\": true,\n\
             \"requires_observation\": true,\n\
             \"required_effects\": [\"local_source_write\", \"remote_deploy\"],\n\
             \"mutation_scope\": \"allowed|read_only|scoped\",\n\
             \"forbidden_actions\": [\"deploy\"],\n\
             \"constraint_evidence\": [\"exact verbatim span from the current user request\"],\n\
             \"tool_scope\": \"allowed|forbidden|restricted\",\n\
             \"allowed_tool_names\": [\"check_environment\"],\n\
             \"forbidden_tool_scopes\": [\"user_memory\"],\n\
             \"tool_constraint_evidence\": [\"exact verbatim span prohibiting all tools or a capability domain\"],\n\
             \"required_response_fields\": [\"exact user-authored output label\"],\n\
             \"minimum_sources\": 0,\n\
             \"requires_primary_sources\": false,\n\
             \"requires_exact_history\": false,\n\
             \"evidence_requirements\": [\n\
               {{\n\
                 \"summary\": \"material fact that must be established\",\n\
                 \"acceptable_scopes\": [\"external_remote\"],\n\
                 \"purpose\": \"current_state|historical_record|content|outcome|attribution|causal_explanation\",\n\
                 \"minimum_authority\": \"advisory|direct|canonical\",\n\
                 \"temporal_scope\": \"current|historical|both\",\n\
                 \"required_content_markers\": [],\n\
                 \"receipt\": {{\n\
                   \"tool_names\": [\"exact required tool identifier\"],\n\
                   \"exit_codes\": [0],\n\
                   \"outcome_statuses\": [\"succeeded|completed_with_negative_result|failed_retryable|failed_permanent|blocked|backgrounded\"],\n\
                   \"requires_output\": false,\n\
                   \"contract_rejected\": false\n\
                 }}\n\
               }}\n\
             ],\n\
             \"required_invocations\": [\n\
               {{\n\
                 \"tool_names\": [\"exact required tool identifier\"],\n\
                 \"exit_codes\": [0],\n\
                 \"outcome_statuses\": [\"succeeded|completed_with_negative_result|failed_retryable|failed_permanent|blocked|backgrounded\"],\n\
                 \"requires_output\": false,\n\
                 \"contract_rejected\": false\n\
               }}\n\
             ],\n\
             \"filesystem_access\": {{\n\
               \"execution_cwd\": null,\n\
               \"read_paths\": [],\n\
               \"write_paths\": []\n\
             }},\n\
             \"project_reference\": null\n\
           }},\n\
           \"task_shape\": {{\n\
             \"execution_mode\": \"inline|durable\",\n\
             \"confidence\": \"low|medium|high\",\n\
             \"independent_workstreams\": 1,\n\
             \"requires_background_continuation\": false,\n\
             \"continue_inline_after_background_start\": false,\n\
             \"request_relationship\": \"new_request|continuation|clarification_answer|courtesy\",\n\
             \"antecedent_user_message_id\": null,\n\
             \"semantic_scope\": \"none|goal_state|user_memory|conversation_history|external_remote|local_workspace|host_local\"\n\
           }}\n\
         }}\n\n\
         Classification rules:\n\
         - Judge meaning, scope, and outcomes in whatever language the user wrote. \
           Do not classify by isolated keywords.\n\
         - execution_mode=inline for answers, lookups, small artifacts, and one \
           cohesive change that the current loop should finish, even when it should \
           run a test afterward.\n\
         - execution_mode=durable only when continuation outside the current run is \
           operationally necessary: explicit background/asynchronous work, waiting on an \
           external condition, monitoring, cross-project work, or multiple genuinely \
           independent workstreams.\n\
         - A long or multi-stage request is not automatically durable. One cohesive target \
           remains inline even when the same agent must build, deploy, verify, and return \
           an external URL. Persistence and task decomposition are separate decisions.\n\
         - continue_inline_after_background_start=true only when starting an asynchronous \
           process leaves another requested action that can run immediately in this same \
           turn without waiting for that process to finish. Otherwise set it false and let \
           the durable completion notification resume dependent work.\n\
         - request_relationship is semantic: use continuation only when this turn advances, \
           retries, or asks about one prior request shown in Recent conversation context; then \
           copy that prior USER row's exact message_id into antecedent_user_message_id. A \
           continuation without that exact ID is invalid. Use null for new_request, courtesy, \
           and clarification_answer. Otherwise use new_request.\n\
         - semantic_scope names the primary typed resource domain, or none. It is independent of \
           request_relationship and must reflect the current request rather than keyword overlap. \
           Multi-domain evidence belongs in evidence_requirements, not in this singular routing hint.\n\
         - expects_mutation=true only when completion changes files or external state. \
           Text generated in the reply is not a mutation.\n\
         - requires_observation=true whenever completion depends on retrieving evidence: live files, \
           commands, web pages, APIs, memory, omitted or exact older conversation history, \
           task/goal/mandate ledgers, or current state. Ordinary adjacent conversation already shown \
           in Recent conversation context is request input, not a new observation obligation. It must \
           be true exactly when evidence_requirements is non-empty.\n\
         - tool_scope=forbidden only when the CURRENT user request explicitly prohibits every \
           tool, lookup, search, browse, or execution path. Preserve requires_observation and \
           evidence_requirements when live evidence would normally be needed; this lets the main \
           model state the exact evidence limitation without violating the constraint. Keep any \
           independently explicit prohibited capability domains in forbidden_tool_scopes so their \
           automatic pipelines and related-turn inheritance remain denied; set allowed_tool_names=[].\n\
         - tool_scope=restricted when the CURRENT request authorizes one or more exact named tools \
           while excluding every other tool (for example, \"use only check_environment\"). Copy only \
           exact tool identifiers present in the current request into allowed_tool_names. This is a \
           hard runtime allowlist, not a suggestion. Otherwise allowed_tool_names=[].\n\
         - When the CURRENT request prohibits only a capability domain, keep tool_scope=allowed \
           and add its typed scope to forbidden_tool_scopes. For example, a no-memory constraint \
           denies user_memory without denying conversation_history or local_workspace. Never infer \
           a deny-set from the topic or an older turn. tool_constraint_evidence must quote exact \
           current-user spans for either kind of prohibition. Otherwise use tool_scope=allowed, \
           forbidden_tool_scopes=[], allowed_tool_names=[], and tool_constraint_evidence=[].\n\
         - required_response_fields contains exact, short labels from the CURRENT user request \
           that must appear in the final answer (requested report keys, columns, verdict labels, \
           or fixed line prefixes). Do not paraphrase, invent, or copy labels from prior tasks; \
           use [] when the user did not specify an output contract.\n\
         - required_effects names the successful effects completion must prove. Valid \
           values are local_source_write, repository_write, remote_mutation, \
           remote_deploy, external_delivery, process_state, configuration, and \
           destructive. Use [] when expects_mutation=false. A build cache or installed \
           dependency is not a local_source_write. Use the narrowest applicable effect: \
           do not add remote_mutation merely because a remote_deploy or external_delivery \
           occurs. Every deliver task must include external_delivery.\n\
         - minimum_sources is the explicit number of distinct source pages required by the \
           request, or 0 when there is no numeric threshold. Set requires_primary_sources \
           only when those sources must be primary.\n\
         - requires_exact_history=true only when completion requires canonical earlier \
           conversation wording rather than ordinary conversational context.\n\
         - evidence_requirements is the completion ledger for independently material subject facts. \
           required_invocations separately lists calls whose occurrence/result is itself requested. \
           Return both [] exactly when requires_observation=false; otherwise at least one list is \
           nonempty. If the current request requires invoking a named tool, command, check, or \
           deliberately invalid call, put its exact machine predicate in required_invocations even \
           when the task is otherwise conversational or rejection/nonzero is the expected result.\n\
         - acceptable_scopes lists alternative authoritative domains for that ONE need. When two \
           domains establish different facts, create two requirements rather than treating them as alternatives.\n\
         - required_content_markers is a legacy compatibility field and must be []. Subject words and \
           response prose are not lifecycle proof. Put exact user-authored output labels in \
           required_response_fields and machine invocation facts in receipt.\n\
         - receipt contains only machine-checkable invocation facts explicitly required by the CURRENT \
           request. tool_names are exact required tool identifiers (not suggestions); exit_codes and \
           outcome_statuses are alternative acceptable results; requires_output means authoritative result \
           content must be nonempty; contract_rejected is the required pre-I/O validation disposition. \
           Omit receipt when no invocation fact is required. Every purpose=outcome entry must have a \
           nonempty receipt and required_content_markers=[]. Never translate receipt facts into prose markers.\n\
         - filesystem_access is the task's least-privilege local access manifest. Put exact local paths \
           the request permits inspecting in read_paths, exact local paths it permits changing in \
           write_paths, and an explicitly requested process working directory in execution_cwd. Paths \
           may appear in both lists. Do not widen a file to its repository, make cwd writable implicitly, \
           or include paths absent from the current request. For non-filesystem tasks use null/[]/[].\n\
         - A current state observation proves only current state/content/outcome. It does not by itself \
           prove who performed an action, why it happened, what the agent previously decided, or whether \
           a historical claim came from autonomous execution. Attribution, causal explanation, and prior \
           execution require a separate historical requirement against an appropriate canonical ledger.\n\
         - Semantic memory and summaries are advisory discovery evidence. Use minimum_authority=advisory \
           only when a summary is genuinely sufficient; use direct for live resources and canonical for exact \
           conversation, task, goal, mandate, or execution-history facts.\n\
         - Split compound questions into material needs. Do not stop at the first answerable clause, and do \
           not add speculative needs unrelated to what the user asked.\n\
         - project_reference is null unless the current request identifies a project or \
           filesystem scope. Otherwise copy only the exact user-authored path or project \
           name; never invent or expand a path.\n\
         - mutation_scope=read_only only when the whole task forbids changes. Use \
           mutation_scope=scoped when the task still requires changes but forbids only \
           named operations. Example: build locally but do not deploy => scoped, \
           expects_mutation=true, forbidden_actions=[\"deploy\"].\n\
         - Valid forbidden_actions values are create, delete, deploy, publish, post, and send. \
           Include only operations actually forbidden by the current request. A content, retry, \
           or precondition guard is not an operation-wide ban: for example, \"do not post \
           secrets\", \"do not post filler\", and \"do not post if identity verification fails\" \
           must not produce forbidden_actions=[\"post\"].\n\
         - mutation_scope=allowed when there is no negative mutation constraint; then \
           forbidden_actions and constraint_evidence must be empty.\n\
         - For read_only or scoped, constraint_evidence must contain the exact verbatim \
           words in the CURRENT user request that impose the restriction. Never derive \
           a restriction from recent conversation context, this prompt's examples, or an \
           inferred phrase that the user did not write.\n\
         {plan_instructions}",
        user_text = truncate_str(user_text, 4000),
    );

    let messages = vec![
        json!({ "role": "system", "content": system }),
        json!({ "role": "user", "content": user_prompt }),
    ];

    let call_start = Instant::now();
    let result = match tokio::time::timeout(
        std::time::Duration::from_secs(15),
        provider.chat(model, &messages, &[]),
    )
    .await
    {
        Ok(Ok(response)) => response,
        Ok(Err(e)) => {
            warn!(error = %e, "Task assessment call failed");
            return None;
        }
        Err(_) => {
            warn!("Task assessment call timed out (15s)");
            return None;
        }
    };
    record_auxiliary_model_call(
        telemetry,
        "task_assessment",
        model,
        &result,
        call_start.elapsed().as_millis() as u64,
    )
    .await;

    let content = result.content.as_deref().unwrap_or("");

    let json_str = match crate::utils::extract_json_object(content) {
        Some(s) => s,
        None => {
            warn!("Task assessment response: no valid JSON found");
            return None;
        }
    };

    let parsed: TaskPlanResponse = match serde_json::from_str(&json_str) {
        Ok(p) => p,
        Err(e) => {
            warn!(error = %e, "Task assessment response unparseable");
            return None;
        }
    };

    let received_schema_version = parsed.schema_version;
    let Some(parsed) = migrate_task_plan_response(parsed) else {
        warn!(
            received = received_schema_version,
            supported = TASK_CONTRACT_SCHEMA_VERSION,
            "Task assessment response used an unsupported schema version"
        );
        return None;
    };

    if parsed.contract.is_none() && parsed.task_shape.is_none() && parsed.steps.is_empty() {
        return None;
    }

    let mut steps = parsed.steps;
    let mut success_criteria = parsed.success_criteria;
    if !mode.includes_step_plan() {
        steps.clear();
        success_criteria.clear();
    }

    steps.truncate(MAX_PLAN_STEPS);

    info!(
        goal = %parsed.goal,
        step_count = steps.len(),
        assessment_mode = mode.as_str(),
        "Task assessment generated"
    );

    Some(TaskPlan {
        goal: parsed.goal,
        steps,
        success_criteria,
        contract: parsed.contract,
        task_shape: parsed.task_shape,
        mode,
    })
}

/// Recover only the typed dialogue edge when the broad task assessment is
/// unavailable. This deliberately cannot produce completion obligations,
/// authority, tool policy, or execution mode. The caller still validates an
/// exact antecedent against persisted dialogue state before committing it.
pub(crate) async fn generate_task_relationship(
    provider: Arc<dyn ModelProvider>,
    model: &str,
    user_text: &str,
    conversation_context: &str,
    telemetry: Option<PlannerTelemetryCtx<'_>>,
) -> Option<PlannedTaskShape> {
    if conversation_context.trim().is_empty() {
        return None;
    }
    let system = "You are a task relationship router. Return only valid JSON. You classify one typed dialogue edge and cannot authorize actions or decide completion.";
    let prompt = format!(
        "Recent conversation with stable message IDs:\n{conversation_context}\n\n\
         Current user request:\n{user_text}\n\n\
         Return exactly: {{\"schema_version\":1,\"confidence\":\"low|medium|high\",\
         \"request_relationship\":\"new_request|continuation|clarification_answer|courtesy\",\
         \"antecedent_user_message_id\":null,\
         \"semantic_scope\":\"none|goal_state|user_memory|conversation_history|external_remote|local_workspace|host_local\"}}.\n\
         Use continuation only when the current request advances, retries, or asks about one prior request shown above; copy that prior USER row's exact message_id. Otherwise use new_request and null. Courtesy and clarification_answer also require null. Judge the whole meaning, not isolated words.",
        conversation_context = truncate_str(conversation_context, 6000),
        user_text = truncate_str(user_text, 4000),
    );
    let messages = vec![
        json!({ "role": "system", "content": system }),
        json!({ "role": "user", "content": prompt }),
    ];
    let call_start = Instant::now();
    let response = match tokio::time::timeout(
        std::time::Duration::from_secs(8),
        provider.chat(model, &messages, &[]),
    )
    .await
    {
        Ok(Ok(response)) => response,
        Ok(Err(error)) => {
            warn!(%error, "Task relationship fallback failed");
            return None;
        }
        Err(_) => {
            warn!("Task relationship fallback timed out (8s)");
            return None;
        }
    };
    record_auxiliary_model_call(
        telemetry,
        "task_relationship_fallback",
        model,
        &response,
        call_start.elapsed().as_millis() as u64,
    )
    .await;

    let json = crate::utils::extract_json_object(response.content.as_deref().unwrap_or(""))?;
    let parsed: TaskRelationshipResponse = serde_json::from_str(&json).ok()?;
    if parsed.schema_version != TASK_RELATIONSHIP_SCHEMA_VERSION
        || !matches!(parsed.confidence.as_str(), "low" | "medium" | "high")
        || !matches!(
            parsed.request_relationship.as_str(),
            "new_request" | "continuation" | "clarification_answer" | "courtesy"
        )
        || !matches!(
            parsed.semantic_scope.as_str(),
            "none"
                | "goal_state"
                | "user_memory"
                | "conversation_history"
                | "external_remote"
                | "local_workspace"
                | "host_local"
        )
    {
        return None;
    }
    let antecedent = parsed
        .antecedent_user_message_id
        .map(|value| value.trim().to_string())
        .filter(|value| !value.is_empty());
    if (parsed.request_relationship == "continuation") != antecedent.is_some() {
        return None;
    }

    Some(PlannedTaskShape {
        execution_mode: None,
        confidence: Some(parsed.confidence),
        independent_workstreams: None,
        requires_background_continuation: None,
        continue_inline_after_background_start: None,
        request_relationship: Some(parsed.request_relationship),
        antecedent_user_message_id: antecedent,
        semantic_scope: Some(parsed.semantic_scope),
    })
}

/// Determine whether a turn bypasses the optional task-start assessment.
/// Semantic task interpretation belongs to the model. Only protocol-level
/// acknowledgments and exact emergency control commands bypass assessment.
#[cfg(test)]
fn should_skip_planning(
    _task_kind: &crate::agent::CompletionTaskKind,
    user_text: &str,
    is_acknowledgment: bool,
) -> bool {
    planning_skip_reason(user_text, is_acknowledgment).is_some()
}

pub(crate) fn planning_skip_reason(
    user_text: &str,
    is_acknowledgment: bool,
) -> Option<&'static str> {
    if is_acknowledgment {
        return Some("acknowledgment");
    }

    // Exact control commands are handled by the typed bootstrap protocol.
    let lower = user_text.trim().to_lowercase();
    let control_commands = [
        "cancel",
        "stop",
        "nevermind",
        "never mind",
        "abort",
        "forget it",
        "forget that",
        "nvm",
    ];
    if control_commands.iter().any(|cmd| lower == *cmd) {
        return Some("control_command");
    }

    None
}

/// Re-planner: evaluates whether the current plan step is complete.
///
/// Called after each tool execution round when the current step has had
/// enough tool calls since the last evaluation. Uses a focused LLM
/// prompt to judge step completion.
///
/// Returns Some(evidence) if the step is complete, None if not or on failure.
pub(crate) async fn evaluate_step_completion(
    provider: Arc<dyn ModelProvider>,
    router: &Router,
    step_description: &str,
    tool_results_summary: &str,
    telemetry: Option<PlannerTelemetryCtx<'_>>,
) -> Option<String> {
    let model = router.select(crate::router::Tier::Primary).to_string();

    let prompt = format!(
        "You are evaluating whether a task step is complete.\n\n\
         Current step: \"{}\"\n\n\
         Tool results from this step:\n{}\n\n\
         Has the agent gathered enough information or completed enough work \
         to move to the next step? Be practical \u{2014} if the key information \
         has been found, the step is complete even if more could theoretically \
         be explored.\n\n\
         Return JSON only:\n\
         {{\"complete\": true/false, \"evidence\": \"brief summary of what was accomplished\"}}",
        step_description,
        truncate_str(tool_results_summary, 1500)
    );

    let messages = vec![
        json!({
            "role": "system",
            "content": "You are a task progress evaluator. Return ONLY valid JSON."
        }),
        json!({ "role": "user", "content": prompt }),
    ];

    let call_start = Instant::now();
    let result = match tokio::time::timeout(
        std::time::Duration::from_secs(10),
        provider.chat(&model, &messages, &[]),
    )
    .await
    {
        Ok(Ok(response)) => response,
        Ok(Err(e)) => {
            warn!(error = %e, "Re-planner call failed");
            return None;
        }
        Err(_) => {
            warn!("Re-planner call timed out (10s)");
            return None;
        }
    };
    record_auxiliary_model_call(
        telemetry,
        "replanner",
        &model,
        &result,
        call_start.elapsed().as_millis() as u64,
    )
    .await;

    let content = result.content.as_deref().unwrap_or("");
    let json_str = crate::utils::extract_json_object(content)?;

    #[derive(Deserialize)]
    struct ReplanResult {
        complete: bool,
        #[serde(default)]
        evidence: String,
    }

    match serde_json::from_str::<ReplanResult>(&json_str) {
        Ok(r) if r.complete => {
            info!(evidence = %r.evidence, "Re-planner: step complete");
            Some(r.evidence)
        }
        Ok(_) => {
            info!("Re-planner: step not yet complete");
            None
        }
        Err(e) => {
            warn!(error = %e, "Re-planner response parse failed");
            None
        }
    }
}

/// Build a summary of recent tool calls for the re-planner prompt.
pub(crate) fn summarize_tool_calls_for_replan(tool_calls: &[String], max_entries: usize) -> String {
    tool_calls
        .iter()
        .rev()
        .take(max_entries)
        .collect::<Vec<_>>()
        .into_iter()
        .rev()
        .map(|call| {
            let display = crate::agent::post_task::display_tool_call(call);
            format!("- {}", display)
        })
        .collect::<Vec<_>>()
        .join("\n")
}

